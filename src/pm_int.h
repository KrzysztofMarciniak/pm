/* pm_int.h - private declarations shared by the libpm sources. */
#ifndef PM_INT_H
#define PM_INT_H

#include "pm/pm.h"

typedef struct {
	char *p;
	size_t len, cap;
} pm_buf;

void pm_buf_init(pm_buf *b);
int pm_buf_add(pm_buf *b, const char *s, size_t n);
int pm_buf_adds(pm_buf *b, const char *s);
char *pm_buf_take(pm_buf *b); /* NUL-terminated, caller frees */
void pm_buf_free(pm_buf *b);

typedef struct {
	char *key;
	char *val;
} pm_kv;

struct pm_ctx {
	pm_kv *vars;
	size_t nvars, capvars;
	pm_kv *tmpl; /* key = name, val = content */
	size_t ntmpl, captmpl;
	char err[512];
	int verbose;
};

char *pm_strdup(const char *s);
void pm_seterr(pm_ctx *c, const char *fmt, ...);
int pm_kv_put(pm_kv **arr, size_t *n, size_t *cap, const char *key, const char *val);
const char *pm_kv_get(const pm_kv *arr, size_t n, const char *key);

/* generated by tools/embed from templates/default.pack */
extern const unsigned char pm_default_pack[];
extern const size_t pm_default_pack_len;

#endif
