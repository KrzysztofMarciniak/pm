/* embed.c - turns a file into a C array: embed <in> <symbol> > out.c
 * Plain C99, no POSIX. A byte array avoids string-literal length limits that
 * small bootstrap compilers impose. */
#include <stdio.h>

int main(int argc, char **argv)
{
	FILE *f;
	int ch;
	unsigned long n = 0;

	if (argc != 3) {
		fprintf(stderr, "usage: embed <file> <symbol>\n");
		return 2;
	}
	f = fopen(argv[1], "rb");
	if (!f) {
		perror(argv[1]);
		return 1;
	}
	printf("/* generated by tools/embed from %s - do not edit */\n", argv[1]);
	printf("#include <stddef.h>\n\nconst unsigned char %s[] = {", argv[2]);
	while ((ch = fgetc(f)) != EOF) {
		if (n % 16 == 0)
			printf("\n\t");
		printf("0x%02x,", (unsigned)ch);
		n++;
	}
	printf("0x00\n};\nconst size_t %s_len = %lu;\n", argv[2], n);
	fclose(f);
	return 0;
}
